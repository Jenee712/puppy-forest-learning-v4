function toUnits(grade: string, courseName: string, seeds: UnitSeed[]): KnowledgeUnit[] {
  return seeds.map(([title, ...knowledgePoints], index) => ({
    id: `${grade}-${courseName}-${index + 1}`,
    title,
    description: `掌握${knowledgePoints.join("、")}`,
    icon: icons[index] ?? "🌟",
    knowledgePoints,
  }));
}

export function getCourseCatalog(grade: string, courseName: string): KnowledgeUnit[] {
  const gradeCatalog = earlyCatalog[grade] ?? schoolCatalog[grade] ?? {};
  const seeds = gradeCatalog[courseName] ?? sharedSchool[courseName] ?? [["认识新知识", "观察", "理解", "练习"], ["动手练一练", "模仿", "应用", "检查"], ["生活中找一找", "发现", "联系", "表达"], ["单元闯关", "整理", "复习", "挑战"]];
  return toUnits(grade, courseName, seeds);
}
